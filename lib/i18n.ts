const ORDERED_PHRASES = [...PHRASES].sort((left, right) => right[0].source.length - left[0].source.length);

export function setMultiPassLanguage(language: MultiPassLanguage | undefined): void {
	activeLanguage = language === "en" ? "en" : "vi";
}

export function getMultiPassLanguage(): MultiPassLanguage {
	return activeLanguage;
}

export function translateUiText(value: string): string {
	if (activeLanguage === "en") return value;
	const exact = VI[value];
	if (exact) return exact;
	for (const [pattern, translate] of PATTERNS) {
		const match = value.match(pattern);
		if (match) return translate(match);
	}
	let translated = value;
	for (const [pattern, replacement] of ORDERED_PHRASES) translated = translated.replace(pattern, replacement);
	return translated;
}

/** Translate only text-bearing UI fields; provider IDs and values stay stable. */
export function translateUiValue(value: unknown): unknown {
	if (typeof value === "string") return translateUiText(value);
	if (Array.isArray(value)) return value.map(translateUiValue);
	if (value && typeof value === "object") {
		const translated = { ...value } as Record<string, unknown>;
		for (const key of ["label", "description", "title", "message", "placeholder"]) {
			if (typeof translated[key] === "string") translated[key] = translateUiText(translated[key] as string);
		}
		return translated;
	}
	return value;
}
